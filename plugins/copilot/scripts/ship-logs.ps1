function Write-ShipDebug {
    param([string]$Message)
    if ($env:ROGUE_DEBUG) { [Console]::Error.WriteLine("[rogue-ship] $Message") }
}

# Our own diagnostics land in the SHIPPING plugin's log file, tagged
# `event=ShipLogs`, and ONLY for notable outcomes (a failure or a skip) - never on
# the happy path, because a line per run would mean every run has new bytes to
# ship, destroying the "an idle machine makes no HTTP request at all" property that
# makes the throttle cheap. It also lands in the file that gets uploaded, so the
# failure it describes becomes readable once shipping recovers.
#
# The shipper NEVER rotates that file even if its own line pushes it over the cap:
# renaming a log we may be part-way through reading is exactly the
# rotation-under-us hazard Get-FirstLineFingerprint re-checks for. Rotation stays
# the dispatcher's job, on its next write.
#
# AppendAllText with an explicit BOM-less UTF-8, never `Add-Content -Encoding
# UTF8`: on Windows PowerShell 5.1 that switch writes a UTF-8 BOM when it creates
# the file, so the first line would start EF BB BF and break any parser anchored on
# the timestamp. "`n" keeps the line ending identical to the sh dispatchers'.
function Write-ShipLog {
    param([string]$Message)
    # ALSO to stderr under ROGUE_DEBUG, and unconditionally - before the selfLogFile
    # gate below. The no-argument support invocation has no slug, so it has no log
    # file of its own to write to, and every failure reason (`http=<code>`,
    # `reason=no-actor`) used to vanish on exactly the run a support engineer is told
    # to make. The file is where the outcome is durable; stderr is where it is visible.
    Write-ShipDebug $Message
    try {
        if (-not $script:selfLogFile) { return }
        $logParentDir = Split-Path $script:selfLogFile
        if ($logParentDir -and -not (Test-Path -LiteralPath $logParentDir)) {
            New-Item -ItemType Directory -Path $logParentDir -Force | Out-Null
        }
        $timeStamp = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
        [System.IO.File]::AppendAllText(
            $script:selfLogFile,
            "$timeStamp provider=$ShipperSlug event=ShipLogs $Message`n",
            (New-Object System.Text.UTF8Encoding($false)))
    } catch {}
}

function ConvertFrom-ShellQuoted {
    # Decode one shell "word" the way ship-logs.sh would when it sources the env
    # file, so values round-trip across both. The files are written either POSIX
    # single-quoted with '\'' escapes (setup.ps1) or via bash printf %q (setup.sh).
    param([string]$Value)
    if ($null -eq $Value) { return $Value }
    $decoded = [System.Text.StringBuilder]::new()
    $index = 0
    $length = $Value.Length
    $state = 'normal'
    while ($index -lt $length) {
        $char = $Value[$index]
        switch ($state) {
            'single' { if ($char -eq "'") { $state = 'normal' } else { [void]$decoded.Append($char) } }
            'double' {
                if ($char -eq '"') { $state = 'normal' }
                elseif ($char -eq '\' -and ($index + 1) -lt $length -and ('"\$`'.IndexOf($Value[$index+1]) -ge 0)) {
                    [void]$decoded.Append($Value[$index+1]); $index++
                }
                else { [void]$decoded.Append($char) }
            }
            default {
                if ($char -eq "'") { $state = 'single' }
                elseif ($char -eq '"') { $state = 'double' }
                elseif ($char -eq '\' -and ($index + 1) -lt $length) { [void]$decoded.Append($Value[$index+1]); $index++ }
                else { [void]$decoded.Append($char) }
            }
        }
        $index++
    }
    return $decoded.ToString()
}

function Get-UserHome {
    $userHome = $env:USERPROFILE
    if (-not $userHome) { $userHome = $HOME }
    if (-not $userHome) { $userHome = '.' }
    return $userHome
}

function Get-EpochSeconds {
    $epoch = New-Object DateTime(1970, 1, 1, 0, 0, 0, [DateTimeKind]::Utc)
    return [int64][Math]::Floor(((Get-Date).ToUniversalTime() - $epoch).TotalSeconds)
}

# Lexical normalisation ONLY - no symlink resolution. `path=` in the state file is
# compared as a STRING by all three implementations, and Node's path.resolve is
# lexical too; resolving links here would make two shippers disagree about the same
# file and re-ship it on alternating runs.
#
# GetFullPath does the same collapsing of redundant separators and `.`/`..`
# segments that path.resolve does, which is what the sh copy had to grow a segment
# walk to match: a bare $PWD-prefix there left `/logs//claude.log` unequal to
# `/logs/claude.log`, so each shipper read the other's state as a DIFFERENT FILE,
# reset the offset and re-shipped the whole log. Never replace this with string
# concatenation.
function Get-NormalizedPath {
    param([string]$Path)
    try { return [System.IO.Path]::GetFullPath($Path) } catch { return $Path }
}

function Get-FileLength {
    param([string]$Path)
    try {
        $fileInfo = Get-Item -LiteralPath $Path -ErrorAction SilentlyContinue
        if ($fileInfo -and -not $fileInfo.PSIsContainer) { return [int64]$fileInfo.Length }
    } catch {}
    return [int64]0
}

# Read [Offset, Offset+Count) as raw bytes. Both share flags are load-bearing and
# for OPPOSITE reasons:
#   * FileShare.ReadWrite, or the read fails intermittently whenever a dispatcher
#     is appending;
#   * FileShare.Delete, or holding the file open makes the dispatcher's Move-Item
#     rotation FAIL - and phase 1 swallows that under -ErrorAction
#     SilentlyContinue, so the log would grow past its cap forever. A log shipper
#     causing unbounded log growth is the worst outcome in this design.
function Read-Range {
    param([string]$Path, [int64]$Offset, [int]$Count)
    # An empty byte[], NOT `, @()` - that returns a one-element array wrapping an
    # empty array, so every downstream .Length check reads 1.
    if ($Count -le 0) { return (New-Object byte[] 0) }
    $stream = $null
    try {
        $buffer = New-Object byte[] $Count
        $stream = New-Object System.IO.FileStream(
            $Path,
            [System.IO.FileMode]::Open,
            [System.IO.FileAccess]::Read,
            ([System.IO.FileShare]::ReadWrite -bor [System.IO.FileShare]::Delete))
        [void]$stream.Seek($Offset, [System.IO.SeekOrigin]::Begin)
        $bytesRead = 0
        while ($bytesRead -lt $Count) {
            $justRead = $stream.Read($buffer, $bytesRead, $Count - $bytesRead)
            if ($justRead -le 0) { break }
            $bytesRead += $justRead
        }
        if ($bytesRead -eq $Count) { return $buffer }
        $shortBuffer = New-Object byte[] $bytesRead
        if ($bytesRead -gt 0) { [Array]::Copy($buffer, 0, $shortBuffer, 0, $bytesRead) }
        return $shortBuffer
    } catch {
        return $null
    } finally {
        if ($stream) { $stream.Dispose() }
    }
}

# Bytes AFTER the last 0x0A: 0 when the chunk already ends on a line boundary, the
# whole length when it holds no newline at all.
function Get-TrailingFragmentLength {
    param([byte[]]$Bytes)
    if (-not $Bytes -or $Bytes.Length -eq 0) { return 0 }
    for ($index = $Bytes.Length - 1; $index -ge 0; $index--) {
        if ($Bytes[$index] -eq 10) { return ($Bytes.Length - 1 - $index) }
    }
    return $Bytes.Length
}

# base64 of the file's FIRST LINE INCLUDING its newline, or '' when no newline
# exists within the first HEAD_WINDOW_BYTES bytes ("unknown" - the caller then falls
# back to `size < offset` alone).
#
# A LINE, not a fixed prefix: logs are append-only, so once a newline exists at
# byte k, bytes 0..k never change again. A fixed 200-byte window instead misfires
# on a young file - one short line hashes N bytes, and once more lines arrive the
# same window spans several, so the head "changes", the offset resets and the file
# is re-shipped every run.
#
# base64 of a byte range, NOT a checksum: all three implementations share
# ~/.rogue/ship/, and a CRC would have to be bit-identical across sh, PowerShell
# and Node, whereas base64 of a byte range is identical everywhere by construction.
function Get-FirstLineFingerprint {
    param([string]$Path)
    $headWindow = Read-Range $Path 0 ($HEAD_WINDOW_BYTES + 1)
    if (-not $headWindow -or $headWindow.Length -eq 0) { return '' }
    $newlineIndex = [Array]::IndexOf($headWindow, [byte]10)
    if ($newlineIndex -lt 0) { return '' }
    $firstLine = New-Object byte[] ($newlineIndex + 1)
    [Array]::Copy($headWindow, 0, $firstLine, 0, $newlineIndex + 1)
    return [Convert]::ToBase64String($firstLine)
}

