# Rogue Security - hook-log shipper (Windows / PowerShell). POSIX sibling:
# ship-logs.sh. Node sibling: plugins/gemini/scripts/ship-logs.mjs.
#
# Uploads the un-shipped tail of this machine's Rogue hook log to
# /api/v1/hooks/logs, so a support engineer can read it WITHOUT an endpoint agent
# on the box. Design, rationale and the state machine: docs/plugin-log-shipper.md.
#
#   ship-logs.ps1 <plugin-root> <shipper-slug> <shipper-version> <agent-family>
#
# NO ARGUMENTS -> collect EVERY known agent's log (ROGUE_SHIP_ALL is implied: with
# no slug there is no "own log" to pick), reporting shipper "unknown".
#
# EDIT scripts/shared/ship-logs.ps1. THIS IS A COMMITTED, BYTE-IDENTICAL COPY of it,
# regenerated by scripts/sync-shared-scripts.sh and verified by
# tests/test_ship_logs.ps1 + `--check` in CI. An edit made here is silently reverted
# by the next sync. (The copies exist, and are committed rather than generated at
# release time, because each plugin installs as a self-contained directory and three
# of them install straight from a git clone with no build step — see the header of
# scripts/sync-shared-scripts.sh.)
#
# Every per-plugin difference is an ARGUMENT; never reference a plugin-specific env
# var here.
#
# Mirrors ship-logs.sh stage for stage so the two can be diffed against each other,
# with three deliberate divergences, each because the sh constraint does not exist
# here:
#   * the chunk lives in a byte[], not a temp file - sh needs the file because sh
#     variables cannot hold NUL bytes, which is not a thing in .NET;
#   * the body is built with ConvertTo-Json -Compress. That is allowed and is NOT
#     what CLAUDE.md forbids: the prohibition is on re-serialising a RELAYED
#     payload (reshaping bytes the server must see verbatim). This body is
#     constructed fresh, so a real serialiser is strictly safer than hand-escaping;
#   * rotation detection reads with FileShare.Delete (see Read-Range).
#
# NAMING: names are spelled out rather than abbreviated, matching ship-logs.sh. The
# sh copy needs a per-function prefix on every temporary because sh has no locals;
# PowerShell function scope makes that unnecessary, so only the SHARED state carries
# the `$script:` qualifier - and it must, or a write from inside a function lands in
# a function-local copy and vanishes with no error (see Initialize-Args).
#
# Fail-open everywhere and always exit 0. PowerShell 5.1-compatible: no `??`, no
# ternaries, no classes.

param(
    [string]$PluginRoot = '',
    [string]$ShipperSlug = '',
    [string]$ShipperVersion = '',
