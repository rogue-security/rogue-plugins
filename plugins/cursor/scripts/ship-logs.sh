#!/usr/bin/env sh
# Rogue Security - hook-log shipper (POSIX sh). Siblings: ship-logs.ps1 (native
# Windows) and plugins/gemini/scripts/ship-logs.mjs (Node).
#
# Uploads the un-shipped tail of this machine's Rogue hook log to
# /api/v1/hooks/logs, so a support engineer can read it WITHOUT an endpoint agent
# on the box. Design, rationale and the state-machine proof: docs/plugin-log-shipper.md.
#
#   sh ship-logs.sh <plugin-root> <shipper-slug> <shipper-version> <agent-family>
#
# NO ARGUMENTS -> collect EVERY known agent's log (ROGUE_SHIP_ALL is implied: with
# no slug there is no "own log" to pick), reporting shipper "unknown". That is the
# support invocation; /rogue:status prints it with the arguments filled in.
#
# EDIT scripts/shared/ship-logs.sh. THIS IS A COMMITTED, BYTE-IDENTICAL COPY of it,
# regenerated by scripts/sync-shared-scripts.sh and verified by
# tests/test_ship_logs.sh + `--check` in CI. An edit made here is silently reverted
# by the next sync.
#
# The copies exist because each plugin is distributed as a SELF-CONTAINED DIRECTORY:
# Cursor, Gemini and Antigravity are installed by copying just their own tree, so on
# a Cursor-only machine nothing outside ~/.cursor/plugins/local/rogue exists and a
# runtime `.`-source of a shared path would find nothing. They are COMMITTED rather
# than generated at release because `claude plugin install` / `codex plugin add` /
# `copilot plugin install` git-clone this monorepo and use plugins/<x>/ with no
# build step at all.
#
# Every per-plugin difference is an ARGUMENT, never a variable read from the
# environment - which is what lets the copies be byte-identical at all. The
# plugin-root var name is the one thing that genuinely differs between them
# (CLAUDE_PLUGIN_ROOT / PLUGIN_ROOT / CURSOR_PLUGIN_ROOT), and the caller already
# holds it. Never reference a plugin-specific env var here.
#
# <agent-family> is passed in and NEVER derived from the slug: the two are
# different vocabularies (codex's log slug is `codex` but its family is `openai`).
# A slug->family table inside a byte-identical script would be one more thing to
# keep in lockstep.
#
# NAMING: POSIX sh has NO LOCAL VARIABLES - every assignment inside a function is
# global. So each function's temporaries are prefixed with a tag for that function
# (`_chunk_*` in ship_next_chunk, `_drain_*` in drain_file, ...). This is not
# decoration: drain_file holds its own file and size while calling ship_next_chunk,
# and a shared bare name like `_file` would be clobbered by the callee and turn the
# drain loop into an infinite one. Add a temporary -> give it the caller's prefix.
# UPPER_CASE names are the deliberately shared state, set by the stages in main().
#
# Fail-open everywhere, `exit 0` on every path, and deliberately NO `set -e`:
#   * non-zero is NORMAL here - curl returns 7 with no network, grep returns 1 on
#     no match - and under `set -e` either would abort mid-run, skipping the state
#     write and the lock release.
#   * a non-zero exit means something to the caller (Copilot's preToolUse is
#     fail-CLOSED), so a broken shipper must be silence, never a failure.
set -u

# ── constants ──────────────────────────────────────────────────────────────
SHIP_ENDPOINT_PATH="/api/v1/hooks/logs"
KNOWN_LOG_SLUGS="claude codex cursor gemini copilot antigravity kiro"
# Bytes scanned when fingerprinting a log's first line. NOT the 200 an earlier
# draft of the design doc specified: a real log line is timestamp + provider +
# event + up to 400 chars of `raw=`, i.e. commonly 500-700 bytes, so a 200-byte
# window would find no newline in the first line of a typical log and the whole
# rotation check would silently never engage.
HEAD_WINDOW_BYTES=4096
# Windows of MAX_LINE_BYTES scanned when hunting the end of an over-long line:
# 256 MiB at the defaults. Past that the file is not a log any more, and the
# shipper stalls rather than advancing (see find_line_end / ship_oversize_line for
# why an advance that does not land after a newline is unsafe at any price).
MAX_SCAN_WINDOWS=64
LOCK_STALE_SECONDS=600
# The same bound in minutes, because the marker-less case ages the lock DIRECTORY
# with `find -mmin` and find has no seconds granularity. Integer division, so keep
# LOCK_STALE_SECONDS a whole number of minutes.
LOCK_STALE_MINUTES=$((LOCK_STALE_SECONDS / 60))
# Hard iteration guard on the chunk loop. MAX_RUN_BYTES/MAX_CHUNK_BYTES is 10 at
# the defaults; this only ever bites if a knob is set to something strange.
MAX_CHUNKS_PER_DRAIN=64
HTTP_TIMEOUT=15

